//! TypeScript bindings for the UI (T45).
//!
//! `app/src/lib/api/*.ts` is generated from the API types and checked in.
//! This test regenerates the bindings into a temporary directory and fails
//! if the checked-in copy differs, so a CI run catches a stale or hand-edited
//! file. After changing an API type, refresh the files with
//!
//! ```sh
//! LAMPSTAND_BLESS=1 cargo test -p lampstand-api --test ts_bindings
//! ```

use std::collections::BTreeMap;
use std::fs;
use std::path::{Path, PathBuf};

use lampstand_api::{Event, Request, Response};
use ts_rs::{Config, TS};

fn checked_in_dir() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR")).join("../../app/src/lib/api")
}

/// Every `*.ts` file in `dir`, by file name. Line endings are normalised so
/// a Windows checkout with `autocrlf` doesn't read as stale.
fn read_ts_files(dir: &Path) -> BTreeMap<String, String> {
    let Ok(entries) = fs::read_dir(dir) else {
        return BTreeMap::new();
    };
    entries
        .map(|e| e.unwrap().path())
        .filter(|p| p.extension().is_some_and(|x| x == "ts"))
        .map(|p| {
            let name = p.file_name().unwrap().to_string_lossy().into_owned();
            (name, fs::read_to_string(&p).unwrap().replace("\r\n", "\n"))
        })
        .collect()
}

/// Writes the bindings for the API's three root types, and everything they
/// reach, into `out`, plus an `index.ts` that re-exports them all.
fn generate(out: &Path) {
    let cfg = Config::new().with_out_dir(out);
    Request::export_all(&cfg).unwrap();
    Response::export_all(&cfg).unwrap();
    Event::export_all(&cfg).unwrap();

    let mut index = String::from(
        "// This file was generated by `cargo test -p lampstand-api --test ts_bindings`. Do not edit.\n\n",
    );
    for name in read_ts_files(out).keys() {
        index.push_str(&format!(
            "export * from \"./{}\";\n",
            name.trim_end_matches(".ts")
        ));
    }
    fs::write(out.join("index.ts"), index).unwrap();
}

#[test]
fn generated_bindings_are_current() {
    let tmp = tempfile::tempdir().unwrap();
    generate(tmp.path());
    let fresh = read_ts_files(tmp.path());
    let dir = checked_in_dir();

    if std::env::var_os("LAMPSTAND_BLESS").is_some() {
        fs::create_dir_all(&dir).unwrap();
        for stale in read_ts_files(&dir).keys() {
            fs::remove_file(dir.join(stale)).unwrap();
        }
        for (name, text) in &fresh {
            fs::write(dir.join(name), text).unwrap();
        }
        return;
    }

    let current = read_ts_files(&dir);
    let missing: Vec<_> = fresh.keys().filter(|n| !current.contains_key(*n)).collect();
    let extra: Vec<_> = current.keys().filter(|n| !fresh.contains_key(*n)).collect();
    let changed: Vec<_> = fresh
        .iter()
        .filter(|(n, t)| current.get(*n).is_some_and(|c| c != *t))
        .map(|(n, _)| n)
        .collect();
    assert!(
        missing.is_empty() && extra.is_empty() && changed.is_empty(),
        "app/src/lib/api is stale (missing {missing:?}, unexpected {extra:?}, changed {changed:?}); \
         run `LAMPSTAND_BLESS=1 cargo test -p lampstand-api --test ts_bindings` and commit the result"
    );
}

#[test]
fn ids_hashes_and_timestamps_map_to_plain_types() {
    let cfg = Config::new();
    assert_eq!(lampstand_core::id::BlobHash::inline(&cfg), "string");
    assert_eq!(lampstand_core::id::Timestamp::inline(&cfg), "number");
    assert_eq!(lampstand_core::song::SongId::inline(&cfg), "string");
}

#[test]
fn serde_tags_are_honoured() {
    let cfg = Config::new();
    // `#[serde(tag = "area", content = "request")]`
    let request = Request::inline(&cfg);
    assert!(
        request.contains("\"area\": \"Library\", \"request\":"),
        "{request}"
    );
    // `#[serde(tag = "type", content = "data")]`
    let response = Response::inline(&cfg);
    assert!(
        response.contains("\"type\": \"Songs\", \"data\":"),
        "{response}"
    );
    assert!(response.contains("\"type\": \"Ok\""), "{response}");
}
